"""Rebuild the Body Oracle train/val/test split so augmented copies never cross splits.

Half of the source photos in `pose_dataset3-1` appear in more than one split: the offline
augmentation wrote `<name>_new` and `<name> flipped` variants of a photo and the split was drawn
per file, so a model can train on one variant and be scored on another. This script groups every
file by its source photo id (`IMG_<number>`), assigns whole groups to splits with class-stratified
sampling, and materialises the result as a symlinked dataset directory plus a `data.yaml`.

Usage:
    Training/.venv/bin/python Tools/training/regroup_split.py \
        Training/pose_dataset3-1 Training/pose_dataset3-1-grouped
"""

from __future__ import annotations

import argparse
import logging
import random
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Set, Tuple

logger = logging.getLogger(__name__)

IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}
SOURCE_RE = re.compile(r"^(IMG[_ ]?\d+)", re.IGNORECASE)
SPLITS = ("train", "valid", "test")
DEFAULT_RATIOS = (0.70, 0.20, 0.10)
NUM_CLASSES = 20

DATA_YAML_TEMPLATE = """# Body Oracle pose dataset, split by source photo (no augmented copy crosses a split).
# Generated by Tools/training/regroup_split.py from {source}

path: {root}
train: images/train
val: images/valid
test: images/test

kpt_shape: [17, 3]
flip_idx: [0, 2, 1, 4, 3, 6, 5, 8, 7, 10, 9, 12, 11, 14, 13, 16, 15]

# WARNING: classes 0 (pose1) and 1 (pose2) are mirror images of each other. Train with
# fliplr=0.0, or horizontal-flip augmentation will relabel one as the other.

nc: 20
names:
{names}
"""


def source_id(stem: str) -> str:
    """Return the source-photo key shared by every variant of one photo."""
    match = SOURCE_RE.match(stem)
    if match is None:
        return f"OTHER:{stem}"
    return match.group(1).upper().replace(" ", "_")


def collect(dataset_root: Path) -> Dict[str, List[Tuple[Path, Path, int]]]:
    """Group (image, label, class id) triples by source photo."""
    groups: Dict[str, List[Tuple[Path, Path, int]]] = defaultdict(list)
    for split in SPLITS:
        images_dir = dataset_root / "images" / split
        if not images_dir.exists():
            continue
        for image_path in sorted(images_dir.iterdir()):
            if image_path.suffix.lower() not in IMAGE_SUFFIXES:
                continue
            label_path = dataset_root / "labels" / split / f"{image_path.stem}.txt"
            if not label_path.exists():
                logger.warning("No label for %s, skipping", image_path.name)
                continue
            class_id = int(float(label_path.read_text().split()[0]))
            groups[source_id(image_path.stem)].append((image_path, label_path, class_id))
    return groups


def assign(
    groups: Dict[str, List[Tuple[Path, Path, int]]],
    ratios: Sequence[float],
    seed: int,
    forced_test: Optional[Set[str]] = None,
) -> Dict[str, str]:
    """Assign each group to a split, stratified by the group's dominant class.

    Groups listed in `forced_test` are pinned to the test split. That is how the evaluation set is
    kept free of photos the previously shipped model was trained on, so old and new models can be
    scored on the same unseen images.
    """
    forced_test = forced_test or set()
    by_class: Dict[int, List[str]] = defaultdict(list)
    for key, members in groups.items():
        dominant = Counter(class_id for _, _, class_id in members).most_common(1)[0][0]
        by_class[dominant].append(key)

    rng = random.Random(seed)
    assignment: Dict[str, str] = {key: "test" for key in forced_test if key in groups}
    for class_id in sorted(by_class):
        keys = sorted(key for key in by_class[class_id] if key not in assignment)
        if not keys:
            continue
        rng.shuffle(keys)
        total = len(keys)
        # Classes that already have pinned test groups need no further test quota.
        pinned = sum(1 for key in by_class[class_id] if assignment.get(key) == "test")
        if total <= 2:
            n_train, n_valid = total, 0
        else:
            n_train = max(1, round(total * ratios[0]))
            remaining = total - n_train
            n_valid = max(1, round(total * ratios[1])) if remaining > 1 else remaining
            if pinned:
                n_train += total - n_train - n_valid  # give the leftover test quota back to train
        for index, key in enumerate(keys):
            if index < n_train:
                assignment[key] = "train"
            elif index < n_train + n_valid:
                assignment[key] = "valid"
            else:
                assignment[key] = "test"
    return assignment


def materialise(
    groups: Dict[str, List[Tuple[Path, Path, int]]],
    assignment: Dict[str, str],
    output_root: Path,
    source_root: Path,
) -> Dict[str, Counter]:
    """Create the symlinked dataset tree and its data.yaml."""
    stats: Dict[str, Counter] = {split: Counter() for split in SPLITS}
    for split in SPLITS:
        (output_root / "images" / split).mkdir(parents=True, exist_ok=True)
        (output_root / "labels" / split).mkdir(parents=True, exist_ok=True)

    for key, members in groups.items():
        split = assignment[key]
        for image_path, label_path, class_id in members:
            for source, kind in ((image_path, "images"), (label_path, "labels")):
                link = output_root / kind / split / source.name
                if link.is_symlink() or link.exists():
                    link.unlink()
                link.symlink_to(source.resolve())
            stats[split][class_id] += 1

    names = "\n".join(f"    {index}: pose{index + 1}" for index in range(NUM_CLASSES))
    (output_root / "data.yaml").write_text(
        DATA_YAML_TEMPLATE.format(source=source_root, root=output_root.resolve(), names=names)
    )
    return stats


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset_root", type=Path)
    parser.add_argument("output_root", type=Path)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--force-test",
        type=Path,
        default=None,
        help="JSON list of image paths whose source groups must land in the test split",
    )
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s")

    groups = collect(args.dataset_root)
    spanning = sum(
        1
        for members in groups.values()
        if len({path.parent.name for path, _, _ in members}) > 1
    )
    logger.info("Source groups: %d (spanning >1 old split: %d)", len(groups), spanning)

    forced_test: Set[str] = set()
    if args.force_test:
        import json

        forced_test = {source_id(Path(entry).stem) for entry in json.loads(args.force_test.read_text())}
        logger.info("Pinning %d source groups to the test split", len(forced_test))

    assignment = assign(groups, DEFAULT_RATIOS, args.seed, forced_test)
    stats = materialise(groups, assignment, args.output_root, args.dataset_root)

    for split in SPLITS:
        logger.info(
            "%-6s groups=%4d images=%4d classes_covered=%d",
            split,
            sum(1 for value in assignment.values() if value == split),
            sum(stats[split].values()),
            len(stats[split]),
        )
    logger.info("Wrote %s", args.output_root / "data.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
